package com.fitpulse.util;

import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.*;

class PasswordHashTest {

    @Test
    void testHashingAndVerification() {
        String plain = "MySecret123!";
        String hash = PasswordUtil.hashPassword(plain);

        assertNotNull(hash);
        assertNotEquals(plain, hash);
        assertTrue(PasswordUtil.verifyPassword(plain, hash));
        assertFalse(PasswordUtil.verifyPassword("wrongpass", hash));
    }

    @Test
    void testNullAndEmptyInputs() {
        assertThrows(IllegalArgumentException.class, () -> PasswordUtil.hashPassword(null));
        assertThrows(IllegalArgumentException.class, () -> PasswordUtil.hashPassword("   "));

        assertFalse(PasswordUtil.verifyPassword(null, "somehash"));
        assertFalse(PasswordUtil.verifyPassword("pass", null));
    }

    @Test
    void testVariantPrefixes() {
        // Mock a $2b$ prefix which is commonly generated by other BCrypt libs (e.g. Python/Node)
        String plain = "testpass";
        String hash2a = PasswordUtil.hashPassword(plain);

        assertTrue(PasswordUtil.verifyPassword(plain, hash2a));

        String hash2b = hash2a.replaceFirst("\\$2a\\$", "\\$2b\\$");
        assertTrue(PasswordUtil.verifyPassword(plain, hash2b));

        String hash2y = hash2a.replaceFirst("\\$2a\\$", "\\$2y\\$");
        assertTrue(PasswordUtil.verifyPassword(plain, hash2y));
    }
}
